import AppKit
import CoreGraphics

/// Types dictated text into the frontmost app by briefly using the clipboard and sending ⌘V.
///
/// Security notes:
/// - Uses the narrow "post events" permission (CGRequestPostEventAccess), which works inside
///   the App Sandbox, rather than full Accessibility control of other apps.
/// - Marks the clipboard entry as concealed/transient so clipboard managers skip it.
/// - Restores the previous clipboard afterwards, but only if nothing else changed it.
@MainActor
enum Paster {
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static var canPaste: Bool { CGPreflightPostEventAccess() }

    /// Shows the system prompt (or opens Privacy & Security if it was declined before).
    static func requestPermission() {
        if !CGRequestPostEventAccess(),
           let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }

    /// Returns false if the text was left on the clipboard because pasting isn't allowed.
    @discardableResult
    static func insert(_ text: String, restoreClipboard: Bool) async -> Bool {
        let pasteboard = NSPasteboard.general
        let saved = restoreClipboard ? snapshot(pasteboard) : nil

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: concealedType)
        pasteboard.setData(Data(), forType: transientType)
        pasteboard.setData(Data(), forType: autoGeneratedType)
        let ourChange = pasteboard.changeCount

        guard canPaste else { return false }
        sendCommandV()

        guard let saved else { return true }
        try? await Task.sleep(for: .milliseconds(400))
        if pasteboard.changeCount == ourChange {
            restore(saved, to: pasteboard)
        }
        return true
    }

    static func copy(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    private static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 0x09
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private static func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    private static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        let items = snapshot.map { pairs -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in pairs {
                item.setData(data, forType: type)
            }
            return item
        }
        pasteboard.writeObjects(items)
    }
}
