// Captures product-tour screenshots of the demo workspace and renders a silent
// explainer video (zoom + captions) with ffmpeg.
// Run after `npm run build && node scripts/copy-export.mjs`.
import http from "node:http";
import { createReadStream, existsSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join, extname, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");

const ROOT = resolve(process.cwd(), "..");
const PORT = 4179;
const MIME = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".wasm": "application/wasm", ".json": "application/json", ".png": "image/png", ".jpg": "image/jpeg", ".svg": "image/svg+xml" };
const server = http.createServer((req, res) => {
  let file = join(ROOT, decodeURIComponent(new URL(req.url, "http://x").pathname));
  if (existsSync(file) && statSync(file).isDirectory()) file = join(file, "index.html");
  if (!existsSync(file)) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { "Content-Type": MIME[extname(file)] ?? "application/octet-stream" });
  createReadStream(file).pipe(res);
});
await new Promise((r) => server.listen(PORT, r));

const OUT = resolve(process.cwd(), "public", "screens");
mkdirSync(OUT, { recursive: true });
const SCENES = [
  { file: "dashboard.png", path: "", caption: "One balance makes every dollar look spendable." },
  { file: "dashboard-alloc.png", path: "", scrollTo: "Revenue and spending", caption: "Six envelopes. Targets, actuals and what is left." },
  { file: "expenses.png", path: "expenses/", caption: "A ceiling on tools. Unspent allowance stays in the business." },
  { file: "personal.png", path: "personal/", caption: "Pay yourself on purpose: household first, then the rest." },
  { file: "trends.png", path: "trends/", caption: "Daily, weekly, monthly, yearly. Watch the result line climb." },
  { file: "month-end.png", path: "month-end/", caption: "Close the month in ten steps. The report writes itself." },
];

const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2, colorScheme: "light" });
await ctx.addInitScript(() => localStorage.setItem("finance-os:theme", "light"));
const page = await ctx.newPage();
await page.goto(`http://localhost:${PORT}/cfoh/app/?demo=1`, { waitUntil: "networkidle" });
await page.getByText("overview").first().waitFor({ timeout: 30000 });
for (const sc of SCENES) {
  await page.goto(`http://localhost:${PORT}/cfoh/app/${sc.path}`, { waitUntil: "networkidle" });
  await page.waitForTimeout(600);
  if (sc.scrollTo) {
    await page.evaluate(() => window.scrollTo({ top: 560 }));
    await page.waitForTimeout(300);
  }
  await page.screenshot({ path: join(OUT, sc.file), fullPage: false });
  console.log("captured", sc.file);
}
await browser.close();
server.close();

// Video: 6 scenes x 6s, slow zoom, caption bar. 1280x800 to keep the file small.
const font = ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"].find((f) => existsSync(f));
const dur = 5;
const fps = 24;
const inputs = [];
const filters = [];
SCENES.forEach((sc, i) => {
  inputs.push("-i", join(OUT, sc.file));
  const text = sc.caption.replace(/'/g, "\\\\'").replace(/:/g, "\\\\:");
  const zoom = `zoompan=z='min(zoom+0.0008,1.12)':x='iw/2-(iw/zoom/2)':y='ih*0.35-(ih/zoom*0.35)':d=${dur * fps}:s=1280x800:fps=${fps}`;
  const caption = font ? `,drawbox=y=ih-150:h=150:color=black@0.55:t=fill,drawtext=fontfile=${font}:text='${text}':fontcolor=white:fontsize=34:x=(w-text_w)/2:y=h-98` : "";
  filters.push(`[${i}:v]scale=1600:1000:force_original_aspect_ratio=increase,crop=1600:1000,${zoom}${caption},fade=t=in:st=0:d=0.4,fade=t=out:st=${dur - 0.4}:d=0.4,setsar=1[v${i}]`);
});
const concat = SCENES.map((_, i) => `[v${i}]`).join("") + `concat=n=${SCENES.length}:v=1:a=0[out]`;
const videoOut = resolve(process.cwd(), "public", "cfoh-demo.mp4");
try {
  execFileSync("ffmpeg", ["-y", "-loglevel", "error", ...inputs, "-filter_complex", filters.join(";") + ";" + concat, "-map", "[out]", "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p", "-crf", "27", "-movflags", "+faststart", videoOut], { stdio: "inherit" });
  const size = statSync(videoOut).size;
  console.log(`video written: ${videoOut} (${(size / 1048576).toFixed(1)} MB)`);
  writeFileSync(resolve(process.cwd(), "public", "screens", "README.txt"), "Generated by scripts/make-tour.mjs from the demo workspace. Re-run after UI changes.\n");
} catch (e) {
  console.error("ffmpeg failed; screenshots are still available", e);
}
