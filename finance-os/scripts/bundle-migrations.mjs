// Bundles drizzle-kit SQL migrations into a TypeScript module so they can run
// inside the browser (sql.js has no filesystem access).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "drizzle");
const journal = JSON.parse(readFileSync(join(dir, "meta", "_journal.json"), "utf8"));
const migrations = journal.entries.map((e) => {
  const sql = readFileSync(join(dir, `${e.tag}.sql`), "utf8");
  const statements = sql
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { tag: e.tag, statements };
});

const out = `// AUTO-GENERATED by scripts/bundle-migrations.mjs. Do not edit by hand.
export interface BundledMigration { tag: string; statements: string[] }
export const MIGRATIONS: BundledMigration[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(join(process.cwd(), "src", "db", "migrations.ts"), out);
console.log(`Bundled ${migrations.length} migration(s) -> src/db/migrations.ts`);
void readdirSync;
